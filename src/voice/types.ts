/** A line of narration in a video's script (written by hand or by the future director). */
export interface NarrationLine {
  id: string;
  text: string;
  /** Start time in seconds. Use `at`, `after` (start after a previous line) or `endAt`. */
  at?: number;
  /** Start `gap` seconds after the line with this id ends. */
  after?: string;
  gap?: number;
  /** Place the line so it ENDS at this time (e.g. land a word on a visual hit). */
  endAt?: number;
  /** Hard deadline: the line must finish before this time (next visual beat). */
  until: number;
  /** Speaking speed multiplier (1 = natural). Auto-raised (max 1.25) if the line doesn't fit. */
  speed?: number;
}

export interface WordTiming { word: string; start: number; end: number }

/** Generated by `npm run voice`; committed so the timeline works without regenerating. */
export interface NarrationTrack {
  voice: string;
  model: string;
  /** "whisper" when word times come from speech recognition, "estimate" otherwise. */
  alignment: "whisper" | "pocketsphinx" | "estimate" | "none";
  lines: { id: string; text: string; file: string; start: number; duration: number; speed: number; words: WordTiming[] }[];
}
